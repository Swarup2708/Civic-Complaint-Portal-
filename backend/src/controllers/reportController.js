const path = require("path");
const Complaint = require("../models/Complaint");
const { generateConsolidatedPDF } = require("../utils/generatePDF");
const sendEmail = require("../utils/sendEmail");

const cleanArea = { $toLower: { $trim: { input: "$area" } } };

exports.generateConsolidatedReport = async (req, res) => {
  try {
    const summary = await Complaint.aggregate([
      {
        $group: {
          _id: { area: cleanArea, category: "$category" },
          count: { $sum: 1 },
          pending: { $sum: { $cond: [{ $eq: ["$status", "Pending"] }, 1, 0] } },
          inProgress: { $sum: { $cond: [{ $eq: ["$status", "In Progress"] }, 1, 0] } },
          resolved: { $sum: { $cond: [{ $eq: ["$status", "Resolved"] }, 1, 0] } },
        },
      },
      { $sort: { "_id.area": 1, "_id.category": 1 } },
    ]);

    if (summary.length === 0) {
      return res.status(400).json({ message: "There are no complaints to report yet" });
    }

    // Top unresolved complaints: zyada upvotes pehle, tie mein purani pehle
    const priority = await Complaint.find({ status: { $ne: "Resolved" } })
      .sort({ upvotes: -1, createdAt: 1 })
      .limit(8)
      .lean();

    // Report ki period: pehli se aakhri complaint tak
    const [range] = await Complaint.aggregate([
      { $group: { _id: null, from: { $min: "$createdAt" }, to: { $max: "$createdAt" } } },
    ]);

    const filePath = path.resolve("uploads", `consolidated-report-${Date.now()}.pdf`);
    await generateConsolidatedPDF(summary, filePath, {
      priority,
      period: range ? { from: range.from, to: range.to } : null,
    });

    const totals = summary.reduce(
      (t, i) => ({
        count: t.count + i.count,
        pending: t.pending + i.pending,
        inProgress: t.inProgress + i.inProgress,
        resolved: t.resolved + i.resolved,
      }),
      { count: 0, pending: 0, inProgress: 0, resolved: 0 }
    );

    const emailText = [
      "Dear Sir/Madam,",
      "",
      "Please find attached the consolidated complaint report generated by the Civic Complaint Portal.",
      "",
      "Summary",
      `  Total complaints : ${totals.count}`,
      `  Pending          : ${totals.pending}`,
      `  In progress      : ${totals.inProgress}`,
      `  Resolved         : ${totals.resolved}`,
      "",
      "The report lists the high-priority unresolved complaints and gives an area-wise and " +
        "category-wise breakdown. We request you to take the necessary action and update the " +
        "status on the portal.",
      "",
      "Regards,",
      "Civic Complaint Portal",
    ].join("\n");

    const emailSent = await sendEmail(
      process.env.MUNICIPAL_EMAIL,
      `Consolidated Complaint Report - ${new Date().toLocaleDateString("en-IN")}`,
      emailText,
      [{ filename: "Consolidated-Complaint-Report.pdf", path: filePath }]
    );

    res.json({
      message: emailSent
        ? "Consolidated report generated and emailed to the municipal office"
        : "Report generated, but the email could not be sent (check .env email settings)",
      emailSent,
      summary,
      filePath,
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// Analytics: category-wise, area-wise, status-wise counts
exports.getAnalytics = async (req, res) => {
  try {
    const [byCategory, byArea, byStatus] = await Promise.all([
      Complaint.aggregate([
        { $group: { _id: "$category", count: { $sum: 1 } } },
        { $sort: { count: -1 } },
      ]),
      Complaint.aggregate([
        { $group: { _id: cleanArea, count: { $sum: 1 } } },
        { $sort: { count: -1 } },
        { $limit: 6 },
      ]),
      Complaint.aggregate([{ $group: { _id: "$status", count: { $sum: 1 } } }]),
    ]);

    const format = (list) => list.map((x) => ({ name: x._id, count: x.count }));

    res.json({
      byCategory: format(byCategory),
      byArea: format(byArea),
      byStatus: format(byStatus),
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};